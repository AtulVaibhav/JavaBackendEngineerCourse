package com.be_practical;

public class TypeCasting {
    public static void main(String[] args) {
        byte a = 100;
        int b = a;
        System.out.println(a+" "+b);


        int x = 120;
        byte y =(byte) x;
        System.out.println(x+" "+y);

        int x1 = 150;
        byte y1 = (byte) x1;
        System.out.println(x1+" "+y1);

    }
}
